-- Esquema de FitoPrice reconstruido a partir del código del backend, el frontend y n8n.
-- No es una copia del esquema original.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Usuarios administradores (sustituye a Supabase Auth)
CREATE TABLE users (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          text NOT NULL UNIQUE,
    password_hash  text NOT NULL,           -- bcrypt
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE companies (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    website     text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE products (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL,
    brand           text,
    category        text,
    unit            text,                   -- L o kg, sacado del nombre (lib/productInfo.js)
    pack_amount     numeric,                -- tamaño del envase en esa unidad
    active_ingredients text[] NOT NULL DEFAULT '{}',  -- materias activas o nutrientes
    product_img_url text,
    created_at      timestamptz NOT NULL DEFAULT now()
);

-- El importador busca cada producto por nombre exacto
CREATE INDEX products_name_idx ON products (name);
CREATE INDEX products_active_ingredients_idx ON products USING gin (active_ingredients);

CREATE TABLE product_prices (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   integer NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    company_id   integer NOT NULL REFERENCES companies (id) ON DELETE CASCADE,
    price        integer NOT NULL,          -- en céntimos
    product_link text,
    scraped_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX product_prices_product_idx ON product_prices (product_id, scraped_at DESC);
CREATE INDEX product_prices_company_idx ON product_prices (company_id);
CREATE INDEX product_prices_scraped_idx ON product_prices (scraped_at DESC);

CREATE TABLE company_urls (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id  integer NOT NULL REFERENCES companies (id) ON DELETE CASCADE,
    url         text NOT NULL,
    active      boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX company_urls_company_idx ON company_urls (company_id);

CREATE TABLE scraping_config (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_url_id  integer NOT NULL UNIQUE REFERENCES company_urls (id) ON DELETE CASCADE,
    selector_card   text,                   -- ficha de cada producto; los demás selectores van dentro
    selector_title  text NOT NULL,
    selector_price  text NOT NULL,
    selector_image  text NOT NULL,
    selector_link   text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);

-- Registro Oficial de Productos Fitosanitarios del Ministerio de Agricultura.
-- Lo carga cada semana el workflow de n8n "registro oficial" (POST /registry/import).
CREATE TABLE registry_products (
    num_registro     text PRIMARY KEY,
    nombre           text NOT NULL,
    nombres          text[] NOT NULL DEFAULT '{}',   -- nombre y otras denominaciones comerciales
    titular          text,
    formulado        text,
    estado           text,
    fecha_caducidad  text,
    composicion      jsonb NOT NULL DEFAULT '[]',    -- [{ sustancia, concentracion, unidad }]
    usos             jsonb NOT NULL DEFAULT '[]',    -- [{ cultivo, agente, dosis_min, dosis_max, unidad, plazo_seguridad, ... }]
    fecha_datos      date,                           -- fecha de la exportación del Ministerio
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- Producto de la tienda -> registro oficial (lo rellena lib/registryMatch.js)
ALTER TABLE products ADD COLUMN registry_num text REFERENCES registry_products (num_registro) ON DELETE SET NULL;
